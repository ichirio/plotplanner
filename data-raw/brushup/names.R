for (n in names(.ard_spec_sheets)) cat(n, ":", paste(.ard_spec_sheets[[n]], collapse = ", "), "\n")
cat("== listing spec sheets\n")
for (n in names(.listing_sheets)) cat(n, ":", paste(.listing_sheets[[n]], collapse = ", "), "\n")
