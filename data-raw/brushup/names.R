ex <- sort(getNamespaceExports("tflspec"))
for (f in ex) { o <- get(f, asNamespace("tflspec")); if (is.function(o)) cat(f, "(", paste(names(formals(o)), collapse = ", "), ")\n") else cat(f, "[object]\n") }
